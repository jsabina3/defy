const stripAccents = (s) =>
  (s || "")
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    // letras nórdicas que NFD no descompone
    .replace(/ø/g, "o").replace(/å/g, "a").replace(/æ/g, "ae");
export const iataFor = (city) => CITY_IATA[stripAccents(city)] || null;
